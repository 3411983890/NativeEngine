import test from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createProjectManager } from '../../editor/project-manager.mjs';
import { writeAssetFixture } from '../../tools/asset-fixtures.mjs';
import { importAsset, attachModel, verifyImport, fitSceneCharacter } from '../../engine/assets/import-service.mjs';
import { reimportAsset } from '../../engine/assets/reimport.mjs';
import { updateSceneImport } from '../../engine/assets/reimport-scene.mjs';
import { loadScene, buildScene } from '../../engine/scene/index.mjs';

test('starter scenes fit, import, reimport and package through their own assets root', async t => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'native-starter-paths-'));
  t.after(() => fs.rm(temporary, { recursive: true, force: true }));
  const manager = createProjectManager({ engineRoot: path.resolve(import.meta.dirname, '../..'), projectsRoot: path.join(temporary, 'projects') });
  const project = await manager.create({ name: '角色资源路径' });
  const scenePath = path.join(project.path, project.scene);
  let scene = await loadScene(scenePath);
  const player = scene.entities.find(e => e.kind === 'player');
  await fitSceneCharacter({ scenePath, entityId: player.id, expectedRevision: 0, mode: 'humanoid' });
  const source = await writeAssetFixture(path.join(temporary, 'source'));
  const asset = await importAsset({ source, output: path.join(temporary, 'imports'), size: 32 });
  await attachModel({ directory: asset.directory, scenePath, expectedRevision: 1 });
  await fs.access(path.join(project.path, 'assets/imported', asset.manifest.id, 'import.json'));
  await assert.rejects(fs.access(path.join(project.path, '.screen/imported')));
  const document = JSON.parse(await fs.readFile(source, 'utf8'));
  document.materials[0].pbrMetallicRoughness.roughnessFactor = .31;
  await fs.writeFile(source, JSON.stringify(document));
  const next = await reimportAsset({ source, directory: asset.directory });
  const updated = await updateSceneImport({ previousDirectory: asset.directory, directory: next.directory, scenePath, expectedRevision: 2 });
  assert.equal(updated.scene.revision, 3);
  assert.ok(updated.report.updatedEntities.length > 0);
  await fs.access(path.join(project.path, 'assets/imported', next.manifest.id, 'import.json'));
  const importedScene = await importAsset({ source: scenePath, output: path.join(temporary, 'scene-imports'), size: 32 });
  assert.equal(importedScene.manifest.kind, 'scene');
  await verifyImport(importedScene.directory);
  const built = await buildScene(scenePath, path.join(project.path, 'build/check'));
  await fs.access(path.join(built.packageDirectory, 'builtin/robot/character.json'));
  await fs.access(path.join(built.packageDirectory, 'textures/engine_grid.albedo.ngtex'));
});
