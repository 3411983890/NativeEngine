export async function writeVegetationFixtures(directory) {
  const target = path.resolve(directory);
  await fs.mkdir(target, { recursive: true });
  // An authored species file wins over the inline recipe. The editor writes to
  // assets/vegetation/species, and the cook reads build/vegetation/source; if the fixture
  // generator kept its own copy the two would drift, which is exactly the "the tree in the
  // editor is not the tree in the viewport" defect. Pine, shrub and grass are still inline
  // because they have no authored file yet.
  const authored = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../assets/vegetation/species');
  const usedAuthored = [];
  for (const entry of species) {
    const authoredFile = path.join(authored, `${entry.id}.species.json`);
    let payload = entry;
    try {
      payload = JSON.parse(await fs.readFile(authoredFile, 'utf8'));
      usedAuthored.push(entry.id);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    await fs.writeFile(path.join(target, `${entry.id}.species.json`), `${JSON.stringify(payload, null, 2)}\n`);
  }
  await fs.writeFile(path.join(target, `${region.id}.region.json`), `${JSON.stringify(region, null, 2)}\n`);
  return { directory: target, species: species.map((entry) => entry.id), authored: usedAuthored, region: region.id };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = process.argv[2] ?? 'build/vegetation/source';
  writeVegetationFixtures(target).then((result) => console.log(JSON.stringify(result))).catch((error) => { console.error(error); process.exitCode = 1; });
}
