import * as fs from 'node:fs/promises';
import path from 'node:path';
import { cookEffectLibrary } from './effects.mjs';
const directory=path.resolve('build/field-host');
const sourceDirectory=path.join(directory,'effects-source');
await fs.mkdir(sourceDirectory,{recursive:true});
const effect=JSON.parse(await fs.readFile('assets/effects/wind_drift.effect.json','utf8'));
const wind=JSON.parse(await fs.readFile('assets/fields/gust_wind.field.json','utf8'));
const write=(file,value)=>fs.writeFile(file,`${JSON.stringify(value,null,2)}\n`);
await write(path.join(sourceDirectory,'wind_drift.effect.json'),effect);
const sprite=JSON.parse(await fs.readFile('assets/effects/sprite_demo.effect.json','utf8'));
await write(path.join(sourceDirectory,'sprite_demo.effect.json'),sprite);
const pulse=structuredClone(effect);pulse.id='wind_pulse';pulse.loop=false;pulse.durationTicks=1;pulse.maxAlive=8;pulse.budget.maxSpawnPerTick=4;pulse.emitters[0].ratePerSecond=0;pulse.emitters[0].bursts=[{tick:0,count:4}];pulse.emitters[0].lifetimeTicks=[2,2];
await write(path.join(sourceDirectory,'wind_pulse.effect.json'),pulse);
const flow=structuredClone(effect);flow.id='flow_drift';flow.field.channels=['waterVelocity'];flow.emitters[0].modules[1].params.channel='waterVelocity';
await write(path.join(sourceDirectory,'flow_drift.effect.json'),flow);
const zero=structuredClone(wind);zero.id='zero_wind';for(const key of zero.tracks.windVelocity)key.metresPerSecond=[0,0,0];
await write(path.join(directory,'zero.field.json'),zero);
await write(path.join(directory,'中文风场.field.json'),wind);
const current=structuredClone(wind);current.id='flow_track';current.tracks={waterVelocity:current.tracks.windVelocity};
await write(path.join(directory,'flow.field.json'),current);
const mismatch=structuredClone(wind);mismatch.id='mismatch_grid';mismatch.cellMetres=.5;
await write(path.join(directory,'mismatch.field.json'),mismatch);
const invalid=structuredClone(wind);invalid.unknown=true;
await write(path.join(directory,'invalid.field.json'),invalid);
const authority=structuredClone(wind);authority.domain='cpu-authority';
await write(path.join(directory,'authority.field.json'),authority);
const result=await cookEffectLibrary({sourceDirectory,outputDirectory:path.join(directory,'cooked')});
console.log(JSON.stringify({packageHash:result.packageHash,library:result.outputDirectory}));
